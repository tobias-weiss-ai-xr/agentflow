#!/bin/bash
# wo-loop — autonomous World Office parity loop (replaces the manual
# one-shot af rounds and the disabled pi-vision wo-agent loop).
#
# Cycle:
#   1. record: mark parked(done)/shelved slugs from receipts
#   2. generate: write the next batch to tasks.json (fresh ids)
#   3. run: `af run --poll 30` — hot-reloads tasks.json/workers.json
#      mid-run; exits only on all-done, deadlock, budget, or `af stop`
#   4. goto 1 (next batch uses a new batch number -> fresh ids; shelved
#      slugs drain the queue forward, so the port never stalls forever)
#
# Stop: `af stop` drains and exits -> loop exits too. Restart: systemd
# Restart=on-failure keeps it alive if it crashes.
set -euo pipefail

LOOP_DIR="${WO_LOOP_DIR:-/home/weiss/.wo-loop}"
STATE_DIR="${WO_STATE_DIR:-$LOOP_DIR/state}"
REPO_DIR="${WO_REPO_DIR:-/home/weiss/git/World-Office/server}"
TASKS_JSON="${LOOP_DIR}/tasks.json"
WORKERS_JSON="${LOOP_DIR}/workers.json"
RUN_LOG="${LOOP_DIR}/run.log"
BATCH_FILE="${LOOP_DIR}/next-batch"
AF="${AF:-/usr/local/bin/af}"

mkdir -p "$LOOP_DIR" "$STATE_DIR"

log() { echo "$(date -Iseconds) $*" | tee -a "$RUN_LOG"; }

# Workers: standing WO parity worker (tud-mistral via 42.42 proxy).
write_workers() {
  cat > "$WORKERS_JSON" <<'EOF'
{
  "_meta": { "round": "wo-auto", "note": "generated by wo-loop" },
  "defaults": { "accept_timeout_s": 3000, "max_attempts": 4, "retry_delay_s": 15, "agent_timeout_s": 7200 },
  "workers": [
    { "name": "tud-mistral", "provider": "openai", "model": "tud/mistral-medium-3.5-128b",
      "api_base": "http://192.168.42.42:4000/v1", "api_key_env": "LITELLM_API_KEY",
      "enabled": true, "cli": "builtin", "max_turns": 96 }
  ]
}
EOF
}

GEN="${LOOP_DIR}/wo-gen-round.py"

next_batch() {
  if [ -f "$BATCH_FILE" ]; then
    cat "$BATCH_FILE"
  else
    echo 1
  fi
}

bump_batch() {
  echo $(($(next_batch) + 1)) > "$BATCH_FILE"
}

# Seed the queue from ledger-gap.md on first run (idempotent).
if [ ! -f "$LOOP_DIR/queue-state.json" ]; then
  python3 "$GEN" --enqueue-all || log "WARN: enqueue-all failed"
fi

BATCH=$(next_batch)

while :; do
  # 1. record outcomes from the LAST run
  if [ -d "$STATE_DIR/receipts" ]; then
    python3 "$GEN" --record "$STATE_DIR" >> "$RUN_LOG" 2>&1 || true
  fi

  # 2. generate this batch
  python3 "$GEN" --batch "$BATCH" --out "$TASKS_JSON" >> "$RUN_LOG" 2>&1
  NT=$(python3 -c "import json;print(len(json.load(open('$TASKS_JSON'))['tasks']))" 2>/dev/null || echo 0)
  log "batch $BATCH: $NT task(s) -> $TASKS_JSON"

  if [ "$NT" -eq 0 ]; then
    log "queue empty/shelved — nothing left to do; exiting"
    exit 0
  fi

  # 3. run
  write_workers
  log "af run --poll 30 (batch $BATCH) ..."
  set +e
  TF_REPO_DIR="$REPO_DIR" TF_STATE_DIR="$STATE_DIR" \
    TF_MAX_PARALLEL=1 \
    "$AF" run --poll 30 \
    --tasks "$TASKS_JSON" \
    --workers "$WORKERS_JSON" \
    >> "$RUN_LOG" 2>&1
  RC=$?
  set -e
  log "af exit=$RC"

  # af stop drains and returns 3 -> stop the loop too (manual stop)
  if [ "$RC" -eq 3 ]; then
    log "af stop requested — loop stopped"
    exit 0
  fi

  bump_batch
  BATCH=$(next_batch)
  sleep 10
done
